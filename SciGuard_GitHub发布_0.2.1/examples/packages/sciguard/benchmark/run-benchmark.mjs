// Local SciGuard SG001 benchmark runner.
// - Loads cases.json, invokes the real checkScientificCode (no Python exec, no model API).
// - Compares actual output against the pre-declared `expected` label.
// - Writes results.json (per-case actuals + pass/fail) and report.md (metrics + failures).
// - Keeps ALL failing cases in the report; never edits detection rules to force a pass.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { checkScientificCode } from '../index.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const projectRoot = join(here, '..', '..', '..', '..')
const cases = JSON.parse(readFileSync(join(here, 'cases.json'), 'utf8'))

// Reconstruct non-JSON placeholder inputs.
function materialize(input) {
  if (input === '__REPEAT_X_32769__') return 'x'.repeat(32769)
  return input
}

// Run one case against the real checker.
function runCase(input) {
  const value = materialize(input)
  try {
    const report = checkScientificCode(value)
    return {
      threw: false,
      throwType: null,
      status: report.status,
      review_required: report.review_required,
      findings: report.findings.length,
      first_finding: report.findings[0] ?? null,
      limitations: report.limitations,
      version: report.version,
    }
  } catch (error) {
    return {
      threw: true,
      throwType: error?.constructor?.name ?? String(error),
      status: null,
      review_required: null,
      findings: null,
      first_finding: null,
      limitations: null,
      version: null,
      error_message: error?.message ?? String(error),
    }
  }
}

// Compare actual against pre-declared expected.
function evaluate(actual, expected) {
  const checks = {}
  if (expected.throws) {
    checks.throws = actual.threw === true
    if (expected.throwsType) checks.throwType = actual.throwType === expected.throwsType
  } else {
    checks.status = actual.status === expected.status
    checks.review_required = actual.review_required === expected.review_required
    checks.findings = actual.findings === expected.findings
  }
  return { ok: Object.values(checks).every(Boolean), checks }
}

const results = cases.map((c) => {
  const actual = runCase(c.input)
  const { ok, checks } = evaluate(actual, c.expected)
  return {
    id: c.id,
    group: c.group,
    expected: c.expected,
    expected_status: c.expected.status,
    expected_throws: c.expected.throws,
    actual,
    passed: ok,
    checks,
    rationale: c.rationale,
  }
})

// ---- Results file (all cases, actuals kept even when failing) ----
mkdirSync(join(projectRoot, 'outputs', 'sciguard-benchmark'), { recursive: true })
writeFileSync(
  join(projectRoot, 'outputs', 'sciguard-benchmark', 'results.json'),
  JSON.stringify({
    generator: 'SciGuard SG001 local benchmark',
    checker_version: results.find((r) => r.actual.version)?.actual.version ?? 'n/a',
    total: results.length,
    passed: results.filter((r) => r.passed).length,
    failed: results.filter((r) => !r.passed).length,
    cases: results,
  }, null, 2),
)

// ---- Metrics ----
function rate(groupResults, filter) {
  if (groupResults.length === 0) return null
  return `${groupResults.filter(filter).length}/${groupResults.length}`
}

const g1 = results.filter((r) => r.group === 'correct_flow')
const g2 = results.filter((r) => r.group === 'leak')
const g3 = results.filter((r) => r.group === 'negative')
const g4 = results.filter((r) => r.group === 'abnormal')

const leakDetected = rate(g2, (r) => r.actual.threw === false && r.actual.status === 'POTENTIAL_RISK')
const correctRate = rate(g1, (r) => r.passed)
const negativePass = rate(g3, (r) => r.passed)
const abnormalHandled = rate(g4, (r) => r.passed)

function failures(list) {
  return list.filter((r) => !r.passed)
}

const md = `# SciGuard SG001 Benchmark Report

Generated by \`examples/packages/sciguard/benchmark/run-benchmark.mjs\`.
Checker under test: \`checkScientificCode\` (SG001), no Python execution, no model API.
Labels are pre-declared in \`cases.json\`; results reflect actual checker behaviour, and failing cases are preserved as-is.

## Summary
- Total cases: ${results.length}
- Passed: ${results.filter((r) => r.passed).length}
- Failed: ${results.filter((r) => !r.passed).length}

## Group-level metrics
| Group | Meaning | Result |
| --- | --- | --- |
| G1 correct_flow | Split first, then fit on the training subset (should NOT alarm) | ${correctRate} passed |
| G2 leak | fit / fit_transform on full data before split (SHOULD alarm) | ${leakDetected} detected as POTENTIAL_RISK |
| G3 negative | Comments / string examples / unrelated datasets (should NOT alarm) | ${negativePass} passed (no false positives) |
| G4 abnormal | empty, whitespace, non-string, oversized, unterminated string | ${abnormalHandled} passed |

Detection rate (leak): ${leakDetected} of G2 found as POTENTIAL_RISK.
False-positive rate (negative): ${g3.filter((r) => r.actual.status === 'POTENTIAL_RISK').length}/${g3.length} G3 cases wrongly alarmed.
Abnormal-input handling rate: ${abnormalHandled} of G4 passed.

## Per-group breakdown
### G1 correct_flow
${g1.map((r) => `- ${r.id}: ${r.passed ? 'PASS' : 'FAIL'} (expected NO_PATTERN_FOUND, actual ${r.actual.threw ? 'threw ' + r.actual.throwType : r.actual.status})`).join('\n')}

### G2 leak
${g2.map((r) => `- ${r.id}: ${r.passed ? 'PASS' : 'FAIL'} (expected POTENTIAL_RISK, actual ${r.actual.threw ? 'threw ' + r.actual.throwType : r.actual.status + ', findings=' + r.actual.findings})`).join('\n')}

### G3 negative
${g3.map((r) => `- ${r.id}: ${r.passed ? 'PASS' : 'FAIL'} (expected NO_PATTERN_FOUND, actual ${r.actual.threw ? 'threw ' + r.actual.throwType : r.actual.status})`).join('\n')}

### G4 abnormal
${g4.map((r) => `- ${r.id}: ${r.passed ? 'PASS' : 'FAIL'} (expected ${r.expected_throws ? 'throw ' + r.expected.throwsType : 'return review_required'}, actual ${r.actual.threw ? 'threw ' + r.actual.throwType : 'returned ' + r.actual.status + ' review_required=' + r.actual.review_required})`).join('\n')}

## Failed cases (preserved)
${failures(results).length === 0
  ? 'None. All cases passed.'
  : failures(results).map((r) => `### ${r.id}\n- expected: ${JSON.stringify({ status: r.expected_status, throws: r.expected_throws })}\n- actual: ${JSON.stringify(r.actual)}\n- rationale: ${r.rationale}`).join('\n\n')}

## Known limitations of this benchmark
- Invokes the heuristic checker only; no execution of the Python under test.
- Comparison is against pre-declared labels, not against the checker's own output.
- G2 detection rate only covers the SG001 pattern (named receiver + first argument); it is not a measure of all possible leakage.
- Failing cases are kept verbatim; detection rules were not modified to increase the pass rate.
`

writeFileSync(join(projectRoot, 'outputs', 'sciguard-benchmark', 'report.md'), md)

// Console summary
console.log(`total=${results.length} passed=${results.filter((r) => r.passed).length} failed=${results.filter((r) => !r.passed).length}`)
console.log(`leak detected=${leakDetected}  G1=${correctRate}  G3=${negativePass}  G4=${abnormalHandled}`)
console.log('wrote outputs/sciguard-benchmark/results.json and report.md')
