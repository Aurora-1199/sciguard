// SciGuard SG001 challenge benchmark runner.
// - Loads challenge/cases.json, invokes the real checkScientificCode (no Python exec, no model API).
// - Each case has a pre-declared `label.leaks` (true = data leakage exists, false = no leakage).
// - The checker returns status === 'POTENTIAL_RISK' with findings >= 1 when it detects a leak.
// - Classification:
//     label.leaks=true  & status=POTENTIAL_RISK  → detected   (true positive)
//     label.leaks=true  & status=NO_PATTERN_FOUND → missed    (false negative)
//     label.leaks=false & status=POTENTIAL_RISK  → false-alarm (false positive)
//     label.leaks=false & status=NO_PATTERN_FOUND → clean     (true negative)
//     threw / error                                         → check-error
// - Writes results.json and report.md to outputs/sciguard-challenge/.
// - Failing cases (missed, false-alarm, check-error) are preserved; detection rules are NOT modified.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { checkScientificCode } from '../../index.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const projectRoot = join(here, '..', '..', '..', '..', '..')
const cases = JSON.parse(readFileSync(join(here, 'cases.json'), 'utf8'))

function runCase(input) {
  try {
    const report = checkScientificCode(input)
    return {
      threw: false,
      throwType: null,
      status: report.status,
      review_required: report.review_required,
      findings: report.findings.length,
      first_finding: report.findings[0] ?? null,
      limitations: report.limitations,
      version: report.version,
    }
  } catch (error) {
    return {
      threw: true,
      throwType: error?.constructor?.name ?? String(error),
      status: null,
      review_required: null,
      findings: null,
      first_finding: null,
      limitations: null,
      version: null,
      error_message: error?.message ?? String(error),
    }
  }
}

function classify(label, actual) {
  if (actual.threw) return 'check_error'
  const detected = actual.status === 'POTENTIAL_RISK' && actual.findings > 0
  if (label.leaks && detected) return 'detected'
  if (label.leaks && !detected) return 'missed'
  if (!label.leaks && detected) return 'false_alarm'
  return 'clean'
}

const results = cases.map((c) => {
  const actual = runCase(c.input)
  const cls = classify(c.label, actual)
  return {
    id: c.id,
    group: c.group,
    label: c.label,
    input: c.input,
    rationale: c.rationale,
    actual,
    classification: cls,
  }
})

// ---- Metrics ----
const detected = results.filter((r) => r.classification === 'detected')
const missed = results.filter((r) => r.classification === 'missed')
const falseAlarm = results.filter((r) => r.classification === 'false_alarm')
const clean = results.filter((r) => r.classification === 'clean')
const checkError = results.filter((r) => r.classification === 'check_error')
const total = results.length

// Precision / recall over non-error cases
const nonError = results.filter((r) => r.classification !== 'check_error')
const tp = detected.length
const fn = missed.length
const fp = falseAlarm.length
const tn = clean.length
const precision = tp + fp > 0 ? tp / (tp + fp) : null
const recall = tp + fn > 0 ? tp / (tp + fn) : null
const accuracy = nonError.length > 0 ? (tp + tn) / nonError.length : null

// ---- Write results.json ----
const outDir = join(projectRoot, 'outputs', 'sciguard-challenge')
mkdirSync(outDir, { recursive: true })

writeFileSync(join(outDir, 'results.json'), JSON.stringify({
  generator: 'SciGuard SG001 challenge benchmark',
  checker_version: results.find((r) => r.actual.version)?.actual.version ?? 'n/a',
  total,
  detected: detected.length,
  missed: missed.length,
  false_alarm: falseAlarm.length,
  clean: clean.length,
  check_error: checkError.length,
  precision,
  recall,
  accuracy,
  cases: results,
}, null, 2))

// ---- Write report.md ----
function section(title, items) {
  if (items.length === 0) return `### ${title}\nNone.\n`
  return `### ${title}\n${items.map((r) =>
    `- **${r.id}** (${r.group}) — expected leak=${r.label.leaks}, actual status=${r.actual.threw ? 'threw ' + r.actual.throwType : r.actual.status + ', findings=' + r.actual.findings}\n  ${r.rationale}`
  ).join('\n')}\n`
}

const failing = [...missed, ...falseAlarm, ...checkError]

const md = `# SciGuard SG001 Challenge Benchmark Report

Generated by \`examples/packages/sciguard/benchmark/challenge/run-challenge.mjs\`.
Checker under test: \`checkScientificCode\` (SG001), no Python execution, no model API.
Labels are pre-declared in \`challenge/cases.json\`; results reflect actual checker behaviour.
Detection rules were NOT modified to force a pass.

## Summary
- Total cases: ${total}
- Detected (TP): ${detected.length}
- Missed (FN): ${missed.length}
- False alarm (FP): ${falseAlarm.length}
- Clean (TN): ${clean.length}
- Check error: ${checkError.length}
- Precision: ${precision !== null ? (precision * 100).toFixed(1) + '%' : 'n/a'}
- Recall: ${recall !== null ? (recall * 100).toFixed(1) + '%' : 'n/a'}
- Accuracy (non-error): ${accuracy !== null ? (accuracy * 100).toFixed(1) + '%' : 'n/a'}

## By group
| Group | Cases | Detected | Missed | False-alarm | Clean | Error |
| --- | --- | --- | --- | --- | --- | --- |
${['import_alias', 'variable_reassignment', 'conditional_branch', 'cross_function_flow', 'similar_no_alarm'].map((g) => {
  const gr = results.filter((r) => r.group === g)
  const cnt = (c) => gr.filter((r) => r.classification === c).length
  return `| ${g} | ${gr.length} | ${cnt('detected')} | ${cnt('missed')} | ${cnt('false_alarm')} | ${cnt('clean')} | ${cnt('check_error')} |`
}).join('\n')}

## Detected (true positive)
${section('Detected', detected)}

## Missed (false negative)
${section('Missed', missed)}

## False alarm (false positive)
${section('False alarm', falseAlarm)}

## Clean (true negative)
${section('Clean', clean)}

## Check error (checker threw)
${section('Check error', checkError)}

## Failing cases (preserved)
${failing.length === 0
  ? 'None. All cases classified correctly.'
  : failing.map((r) => `### ${r.id}
- expected: leak=${r.label.leaks}
- actual: ${JSON.stringify({ status: r.actual.status, threw: r.actual.threw, throwType: r.actual.throwType, findings: r.actual.findings })}
- classification: ${r.classification}
- rationale: ${r.rationale}
- input: \`\`\`python
${r.input}
\`\`\``).join('\n\n')}

## Recommended priority fix
${(() => {
  if (failing.length === 0) return 'No failing cases.'
  // Prioritise: missed leaks first (safety-critical), then check errors, then false alarms.
  const priority = [
    ...missed.map((r) => ({ r, kind: 'missed', score: 3 })),
    ...checkError.map((r) => ({ r, kind: 'check-error', score: 2 })),
    ...falseAlarm.map((r) => ({ r, kind: 'false-alarm', score: 1 })),
  ].sort((a, b) => b.score - a.score || a.r.id.localeCompare(b.r.id))
  const top = priority[0]
  const r = top.r
  const reasonByKind = {
    missed: 'A missed leak is safety-critical: the checker fails to flag a genuine data-leakage pattern, so downstream model evaluation may be silently biased. This should be fixed before reducing false alarms.',
    'check-error': 'A checker exception means the tool is broken for this input shape; it must be handled gracefully to avoid blocking all code review.',
    'false-alarm': 'A false alarm wastes reviewer time on correct code; reducing it improves trust but is less urgent than missing a real leak.',
  }
  return `**${r.id}** (${r.group}) — ${top.kind}\n\nReason: ${reasonByKind[top.kind]}\n\nChecker status: ${r.actual.threw ? 'threw ' + r.actual.throwType : r.actual.status + ', findings=' + r.actual.findings}\nExpected: leak=${r.label.leaks}\n\nCode:\n\`\`\`python\n${r.input}\n\`\`\`\n\n${r.rationale}`
})()}

## Known limitations
- Invokes the heuristic checker only; no execution of the Python under test.
- Labels are manually pre-declared; a "missed" case does not prove the checker is wrong, only that it did not flag a known-leak pattern.
- The checker (SG001) assumes straight-line code with named sklearn-style calls; branch/function/alias cases may be out of its design scope.
- Failing cases are preserved verbatim; detection rules were not modified.
`

writeFileSync(join(outDir, 'report.md'), md)

// Console summary
console.log(`total=${total} detected=${detected.length} missed=${missed.length} false_alarm=${falseAlarm.length} clean=${clean.length} check_error=${checkError.length}`)
console.log(`precision=${precision !== null ? (precision * 100).toFixed(1) + '%' : 'n/a'} recall=${recall !== null ? (recall * 100).toFixed(1) + '%' : 'n/a'} accuracy=${accuracy !== null ? (accuracy * 100).toFixed(1) + '%' : 'n/a'}`)
console.log('wrote outputs/sciguard-challenge/results.json and report.md')
